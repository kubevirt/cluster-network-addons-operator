type goSource struct {
	imports map[string]string
}

func generateGo(component string, objects []*unstructured.Unstructured) ([]byte, error) {
	source := &goSource{imports: map[string]string{
		"k8s.io/utils/ptr": "ptr",
	}}
	var declarations strings.Builder
	for _, object := range objects {
		if object == nil || len(object.Object) == 0 {
			continue
		}
		objectType, err := source.objectType(object)
		if err != nil {
			return nil, errors.Wrapf(err, "generate HCO Go type for %s %s", object.GetKind(), object.GetName())
		}
		expression, err := source.objectLiteral(object)
		if err != nil {
			return nil, errors.Wrapf(err, "generate HCO Go for %s %s", object.GetKind(), object.GetName())
		}
		name := constructorName(component, object)
		fmt.Fprintf(&declarations, "\n// %s creates the rendered %s %q for the %s output.\n", name, object.GetKind(), object.GetName(), component)
		fmt.Fprintf(&declarations, "func %s() %s {\n\treturn %s\n}\n", name, objectType, expression)
	}

	var output strings.Builder
	output.WriteString("// Code generated by cnao-render; DO NOT EDIT.\n\npackage generated\n\nimport (\n")
	paths := make([]string, 0, len(source.imports))
	for path := range source.imports {
		paths = append(paths, path)
	}
	sort.Strings(paths)
	for _, path := range paths {
		fmt.Fprintf(&output, "\t%s %q\n", source.imports[path], path)
	}
	output.WriteString(")\n\n")
	output.WriteString(declarations.String())
	formatted, err := format.Source([]byte(output.String()))
	if err != nil {
		return nil, errors.Wrap(err, "format generated HCO Go source")
	}
	return formatted, nil
}

func (s *goSource) objectType(object *unstructured.Unstructured) (string, error) {
	if object.GroupVersionKind().Group == "security.openshift.io" && object.GetKind() == "SecurityContextConstraints" {
		s.imports["github.com/openshift/api/security/v1"] = "securityv1"
		return "*securityv1.SecurityContextConstraints", nil
	}
	target := typedObject(object.GroupVersionKind())
	if target == nil {
		s.imports["k8s.io/apimachinery/pkg/apis/meta/v1/unstructured"] = "unstructured"
		return "*unstructured.Unstructured", nil
	}
	return s.typeName(reflect.TypeOf(target)), nil
}

func constructorName(component string, object *unstructured.Unstructured) string {
	return "New" + exportedName(component) + exportedName(object.GetKind()) + exportedName(object.GetName())
}

func exportedName(value string) string {
	var name strings.Builder
	capitalize := true
	for _, r := range value {
		if !((r >= 'a' && r <= 'z') || (r >= 'A' && r <= 'Z') || (r >= '0' && r <= '9')) {
			capitalize = true
			continue
		}
		if capitalize {
			if r >= 'a' && r <= 'z' {
				r -= 'a' - 'A'
			}
			capitalize = false
		}
		name.WriteRune(r)
	}
	return name.String()
}

func (s *goSource) objectLiteral(object *unstructured.Unstructured) (string, error) {
	if object.GroupVersionKind().Group == "security.openshift.io" && object.GetKind() == "SecurityContextConstraints" {
		return s.securityContextConstraintsLiteral(object.Object)
	}
	target := typedObject(object.GroupVersionKind())
	if target == nil {
		s.imports["k8s.io/apimachinery/pkg/apis/meta/v1/unstructured"] = "unstructured"
		literal, err := s.value(reflect.ValueOf(object.Object), false)
		if err != nil {
			return "", err
		}
		return "&unstructured.Unstructured{Object: " + literal + "}", nil
	}
	fields := make(map[string]interface{}, len(object.Object))
	for key, value := range object.Object {
		if key != "apiVersion" && key != "kind" {
			fields[key] = value
		}
	}
	if err := runtime.DefaultUnstructuredConverter.FromUnstructured(fields, target); err != nil {
		return "", errors.Wrap(err, "convert manifest to Kubernetes type")
	}
	literal, err := s.value(reflect.ValueOf(target), false)
	if err != nil {
		return "", err
	}
	if configMap, ok := target.(*corev1.ConfigMap); ok && configMap.Name == "kubemacpool-mac-range-config" {
		for key, envVar := range map[string]string{
			"RANGE_START": "KUBEMACPOOL_RANGE_START",
			"RANGE_END":   "KUBEMACPOOL_RANGE_END",
		} {
			if value, exists := configMap.Data[key]; exists {
				literal = strings.Replace(literal, strconv.Quote(value), "os.Getenv("+strconv.Quote(envVar)+")", 1)
				s.imports["os"] = "os"
			}
		}
	}
	return literal, nil
}

