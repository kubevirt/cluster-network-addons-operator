func (s *goSource) value(value reflect.Value, nested bool) (string, error) {
	if !value.IsValid() {
		return "nil", nil
	}
	if value.Kind() == reflect.Interface {
		if value.IsNil() {
			return "nil", nil
		}
		return s.value(value.Elem(), nested)
	}
	if value.Kind() == reflect.Pointer {
		if value.IsNil() {
			return "nil", nil
		}
		element := value.Elem()
		literal, err := s.value(element, false)
		if err != nil {
			return "", err
		}
		switch element.Kind() {
		case reflect.String, reflect.Bool, reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64,
			reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64, reflect.Float32, reflect.Float64:
			literal = s.typeName(element.Type()) + "(" + literal + ")"
		}
		return "ptr.To(" + literal + ")", nil
	}
	if value.CanInterface() {
		switch typed := value.Interface().(type) {
		case resource.Quantity:
			s.imports["k8s.io/apimachinery/pkg/api/resource"] = "resource"
			return "resource.MustParse(" + strconv.Quote(typed.String()) + ")", nil
		case intstr.IntOrString:
			s.imports["k8s.io/apimachinery/pkg/util/intstr"] = "intstr"
			if typed.Type == intstr.String {
				return "intstr.FromString(" + strconv.Quote(typed.StrVal) + ")", nil
			}
			return fmt.Sprintf("intstr.FromInt(%d)", typed.IntVal), nil
		case time.Time:
			s.imports["time"] = "time"
			return fmt.Sprintf("time.Date(%d, time.%s, %d, %d, %d, %d, %d, time.FixedZone(%q, %d))", typed.Year(), typed.Month(), typed.Day(), typed.Hour(), typed.Minute(), typed.Second(), typed.Nanosecond(), typed.Location().String(), zoneOffset(typed)), nil
		}
	}

	switch value.Kind() {
	case reflect.Struct:
		return s.structLiteral(value, nested)
	case reflect.Map:
		return s.mapLiteral(value)
	case reflect.Slice, reflect.Array:
		if value.Kind() == reflect.Slice && value.IsNil() {
			return "nil", nil
		}
		parts := make([]string, 0, value.Len())
		for i := 0; i < value.Len(); i++ {
			part, err := s.value(value.Index(i), true)
			if err != nil {
				return "", err
			}
			parts = append(parts, part)
		}
		if len(parts) == 0 {
			return s.typeName(value.Type()) + "{}", nil
		}
		return s.typeName(value.Type()) + "{\n" + indentGo(strings.Join(parts, ",\n")) + ",\n}", nil
	case reflect.String:
		return strconv.Quote(value.String()), nil
	case reflect.Bool:
		return strconv.FormatBool(value.Bool()), nil
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64:
		return strconv.FormatInt(value.Int(), 10), nil
	case reflect.Uint, reflect.Uint8, reflect.Uint16, reflect.Uint32, reflect.Uint64:
		return strconv.FormatUint(value.Uint(), 10), nil
	case reflect.Float32, reflect.Float64:
		return strconv.FormatFloat(value.Float(), 'g', -1, value.Type().Bits()), nil
	}
	return "", fmt.Errorf("unsupported Go value type %s", value.Type())
}

func (s *goSource) structLiteral(value reflect.Value, nested bool) (string, error) {
	typeName := s.typeName(value.Type())
	fields := make([]string, 0, value.NumField())
	typeOf := value.Type()
	for i := 0; i < value.NumField(); i++ {
		fieldType := typeOf.Field(i)
		field := value.Field(i)
		if fieldType.PkgPath != "" || field.IsZero() {
			continue
		}
		literal, err := s.value(field, false)
		if err != nil {
			return "", errors.Wrapf(err, "field %s", fieldType.Name)
		}
		fields = append(fields, fieldType.Name+": "+literal)
	}
	if len(fields) == 0 {
		if nested {
			return "{}", nil
		}
		return typeName + "{}", nil
	}
	literal := "{\n" + indentGo(strings.Join(fields, ",\n")) + ",\n}"
	if nested {
		return literal, nil
	}
	return typeName + literal, nil
}

func (s *goSource) mapLiteral(value reflect.Value) (string, error) {
	if value.IsNil() {
		return "nil", nil
	}
	keys := value.MapKeys()
	sort.Slice(keys, func(i, j int) bool { return fmt.Sprint(keys[i].Interface()) < fmt.Sprint(keys[j].Interface()) })
	entries := make([]string, 0, len(keys))
	for _, key := range keys {
		keyLiteral, err := s.value(key, false)
		if err != nil {
			return "", err
		}
		valueLiteral, err := s.value(value.MapIndex(key), true)
		if err != nil {
			return "", err
		}
		entries = append(entries, keyLiteral+": "+valueLiteral)
	}
	if len(entries) == 0 {
		return s.typeName(value.Type()) + "{}", nil
	}
	return s.typeName(value.Type()) + "{\n" + indentGo(strings.Join(entries, ",\n")) + ",\n}", nil
}

func indentGo(value string) string {
	return "\t" + strings.ReplaceAll(value, "\n", "\n\t")
}

func (s *goSource) typeName(t reflect.Type) string {
	for t.Kind() == reflect.Pointer || t.Kind() == reflect.Slice || t.Kind() == reflect.Array || t.Kind() == reflect.Map {
		switch t.Kind() {
		case reflect.Pointer:
			return "*" + s.typeName(t.Elem())
		case reflect.Slice:
			return "[]" + s.typeName(t.Elem())
		case reflect.Array:
			return fmt.Sprintf("[%d]%s", t.Len(), s.typeName(t.Elem()))
		case reflect.Map:
			return "map[" + s.typeName(t.Key()) + "]" + s.typeName(t.Elem())
		}
	}
	if t.Name() == "" {
		return t.String()
	}
	if t.PkgPath() == "" {
		return t.Name()
	}
	alias := packageAlias(t.PkgPath())
	s.imports[t.PkgPath()] = alias
	return alias + "." + t.Name()
}

func packageAlias(path string) string {
	if alias, ok := map[string]string{
		"k8s.io/api/admissionregistration/v1":                      "admissionregistrationv1",
		"k8s.io/apiextensions-apiserver/pkg/apis/apiextensions/v1": "apiextensionsv1",
		"k8s.io/api/apps/v1":                                       "appsv1",
		"k8s.io/api/core/v1":                                       "corev1",
		"k8s.io/api/networking/v1":                                 "networkingv1",
		"k8s.io/api/policy/v1":                                     "policyv1",
		"k8s.io/api/rbac/v1":                                       "rbacv1",
		"k8s.io/apimachinery/pkg/api/resource":                     "resource",
		"k8s.io/apimachinery/pkg/apis/meta/v1":                     "metav1",
		"k8s.io/apimachinery/pkg/runtime":                          "runtime",
		"k8s.io/apimachinery/pkg/util/intstr":                      "intstr",
		"github.com/k8snetworkplumbingwg/network-attachment-definition-client/pkg/apis/k8s.cni.cncf.io/v1": "netattdefv1",
		"github.com/prometheus-operator/prometheus-operator/pkg/apis/monitoring/v1":                        "monitoringv1",
		"time": "time",
	}[path]; ok {
		return alias
	}
	parts := strings.Split(path, "/")
	return strings.ReplaceAll(parts[len(parts)-1], "-", "")
}

func zoneOffset(t time.Time) int {
	_, offset := t.Zone()
	return offset
}
